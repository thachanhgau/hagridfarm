// Pack authored water-surface poses separately from the full-body collection/portrait sprites.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {authoredCells} from './authored-atlas.mjs';
import {rasterize} from './build-creature-motion.mjs';
import {packNativeAtlas} from './native-atlas.mjs';
const root=path.dirname(fileURLToPath(import.meta.url)),require=createRequire(import.meta.url);
const sharp=require(process.env.SHARP_MODULE||'/Users/thachanh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const file='creature-motion-assets/masters/submerged-20261108/provenance.json';
const manifest=JSON.parse(await fs.readFile(path.join(root,file),'utf8')),art={};
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
for(const spec of manifest.species){
 const bytes=await fs.readFile(path.join(root,spec.master));if(hash(bytes)!==spec.masterSha256)throw Error('Master provenance '+spec.id);
 const poses=authoredCells(await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true}),[4,4]);
 const median=a=>a.sort((a,b)=>a-b)[Math.floor(a.length/2)],adult=poses.slice(4);
 const scale=Math.min(76/median(adult.map(p=>p.mainBounds.w)),52/median(adult.map(p=>p.mainBounds.h)));
 const growthScale=Math.min(76/poses[3].mainBounds.w,52/poses[3].mainBounds.h);
 const canvas={width:128,height:96,pivotX:64,pivotY:64},target={w:80,h:56},views={left:[],right:[]};
 for(const [index,pose]of poses.entries()){
  const r=rasterize(pose,canvas,target,index<4?growthScale:scale,new Map());
  if(r.clippedPixels)throw Error(spec.id+' clipped pose '+index);
  const right=await sharp(r.output,{raw:{width:128,height:96,channels:4}}).png().toBuffer();
  for(const direction of ['left','right']){
   const png=direction==='right'?right:await sharp(right).flop().png().toBuffer();
   const frameFile=`creature-motion-assets/submerged-native/${spec.id}/${direction}-${index}.png`;
   await fs.mkdir(path.dirname(path.join(root,frameFile)),{recursive:true});await fs.writeFile(path.join(root,frameFile),png);
   views[direction].push({file:frameFile,...canvas,bounds:direction==='right'?r.bounds:{...r.bounds,x:128-r.bounds.x-r.bounds.w},sha256:hash(png)});
  }
 }
 art[spec.id]={};spec.frames=views;spec.atlases={};
 for(const direction of ['left','right']){
  const atlas=await packNativeAtlas(root,`creature-motion-assets/native/${spec.id}/submerged-${direction}-atlas.png`,views[direction]);
  art[spec.id][direction]=atlas.frames;spec.atlases[direction]={file:atlas.file,sha256:atlas.sha256};
 }
 console.log(spec.id,'8 poses × 2 views, anchored at waterline (64,64)');
}
const module=`// Generated by build-submerged-creatures.mjs. Waterline pivot, not a dry-land foot.\nexport const SUBMERGED_CREATURE_ART=${JSON.stringify(art)};\nexport const SUBMERGED_CREATURE_FILES=[...new Set(Object.values(SUBMERGED_CREATURE_ART).flatMap(a=>Object.values(a).flatMap(frames=>frames.map(f=>f.file))))];\nexport function submergedCreatureFrame(species,stage,clock=0,facing='default'){\n const frames=SUBMERGED_CREATURE_ART[species]?.[facing==='right'?'right':'left'];\n if(!frames)return null;\n const age=Math.max(0,Math.min(3,Math.round(Number(stage)||0)));\n if(age<3||!(clock>0))return frames[age];\n let t=clock%1260;\n const durations=[600,240,180,240];\n for(let i=0;i<4;i++){if(t<durations[i])return frames[4+i];t-=durations[i];}\n return frames[4];\n}\n`;
await fs.writeFile(path.join(root,'pond-creature-art.mjs'),module);
await fs.writeFile(path.join(root,file),JSON.stringify(manifest,null,2)+'\n');
