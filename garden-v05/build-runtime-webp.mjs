// Keep authored PNGs intact; publish a separate, pixel-identical WebP runtime pack.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const root=path.dirname(fileURLToPath(import.meta.url)),require=createRequire(import.meta.url);
const sharp=require(process.env.SHARP_MODULE||'/Users/thachanh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
sharp.concurrency(1);
const folders=['native','native-levels','native-care','native-items','native-complete-objects','native-crop-complete','creature-motion-assets/native','decor-assets','environment','v24-art','world-v241','world-v242'];
const skip=/(^|\/)(masters\/|prompts\.json$|provenance\.json$)|^decor-assets\/qa\/|^native-crop-complete\/[^/]+\/frame-\d+\.png$|^creature-motion-assets\/native\/[^/]+\/(?:left|right)-(?:growth|idle|action|eat|care)-\d+\.png$|^environment\/(garden-background|garden-native|terrain-grass|terrain-soil|hut|props-v03)\.png$/;
const digest=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const read=relative=>fs.readFile(path.join(root,relative));
async function list(relative){
 const files=[];
 for(const entry of (await fs.readdir(path.join(root,relative),{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
  const file=relative+'/'+entry.name;if(skip.test(file))continue;
  if(entry.isDirectory())files.push(...await list(file));else if(/\.(png|webp)$/i.test(file))files.push(file);
 }
 return files;
}
const paths=(await Promise.all(folders.map(list))).flat();
const pngs=paths.filter(file=>file.endsWith('.png')),existing=paths.filter(file=>file.endsWith('.webp'));
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(arg=>arg!=='--check'))throw Error('Usage: node build-runtime-webp.mjs [--check]');
if(check){
 const manifest=JSON.parse(await read('runtime-webp-manifest.json'));
 assert.deepEqual(manifest.images.map(image=>image.source),pngs,'rebuild WebP after changing the PNG inventory');
 assert.deepEqual(manifest.existingWebp.map(image=>image.file),existing,'rebuild WebP manifest after changing existing WebP');
 for(const image of manifest.images){assert.equal(digest(await read(image.source)),image.sourceSha256,image.source);assert.equal(digest(await read(image.file)),image.sha256,image.file);}
 for(const image of manifest.existingWebp)assert.equal(digest(await read(image.file)),image.sha256,image.file);
 console.log(`WebP pack verified: ${pngs.length} lossless conversions + ${existing.length} existing WebP.`);
 process.exit(0);
}
const images=Array(pngs.length);let next=0,done=0;
await Promise.all(Array.from({length:4},async()=>{
 while(next<pngs.length){
  const index=next++,source=pngs[index],input=await read(source);
  const file='runtime-webp/'+source.replace(/\.png$/,'.webp');
  const output=await sharp(input).webp({lossless:true,exact:true,effort:6}).toBuffer();
  const before=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const after=await sharp(output).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  assert.equal(after.info.width,before.info.width,source);assert.equal(after.info.height,before.info.height,source);
  assert.ok(before.data.equals(after.data),`${source}: decoded RGBA differs`);
  await fs.mkdir(path.dirname(path.join(root,file)),{recursive:true});await fs.writeFile(path.join(root,file),output);
  images[index]={source,file,width:before.info.width,height:before.info.height,sourceBytes:input.length,bytes:output.length,sourceSha256:digest(input),sha256:digest(output)};
  if(++done%150===0)console.log(`Verified ${done}/${pngs.length} images (RGBA identical).`);
 }
}));
const existingWebp=await Promise.all(existing.map(async file=>{const bytes=await read(file);return {file,bytes:bytes.length,sha256:digest(bytes)};}));
const revision=digest(Buffer.from(images.map(image=>image.source+':'+image.sha256).join('\n'))).slice(0,12);
const sum=(rows,key)=>rows.reduce((total,row)=>total+row[key],0),existingBytes=sum(existingWebp,'bytes');
const originalBytes=sum(images,'sourceBytes')+existingBytes,webpBytes=sum(images,'bytes')+existingBytes;
const manifest={version:1,pngConversion:{lossless:true,exactTransparentRgb:true,decodedRgbaIdentical:true},revision,sourceFolders:folders,images,existingWebp,totals:{converted:images.length,existingWebp:existingWebp.length,originalBytes,webpBytes,savedBytes:originalBytes-webpBytes,savedPercent:Number((100*(originalBytes-webpBytes)/originalBytes).toFixed(2))}};
await fs.writeFile(path.join(root,'runtime-webp-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
const pattern='^(?:\\./)?(('+folders.join('|')+')/[^?#]+)\\.png(?:[?#].*)?$';
await fs.writeFile(path.join(root,'runtime-image-url.mjs'),`// Generated by build-runtime-webp.mjs. Original manifests/pivots stay unchanged.\nexport const WEBP_REVISION=${JSON.stringify(revision)};\nconst png=new RegExp(${JSON.stringify(pattern)});\nexport function runtimeImageUrl(value){\n const match=typeof value==='string'&&png.exec(value);\n return match?'runtime-webp/'+match[1]+'.webp?v='+WEBP_REVISION:value;\n}\n`);
console.log(JSON.stringify(manifest.totals));
