// Derive idle and action frames for crops that only shipped growth frames
// (docs/art-bible.md section 5). Each new frame moves whole pixel rows of the
// authored mature frame: the top sways or rises, the base rows never move, no
// pixel is resampled and no colour is added. Output: native-levels/<id>/frame-05..11.png,
// idle-assets-manifest.json and motion-idle-data.js (patches FARM_MOTION at load).
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
// Loaded lazily so tests can import the pure pose function without the image library.
const loadSharp = () => require(process.env.SHARP_MODULE || '/Users/thachanh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root = path.dirname(fileURLToPath(import.meta.url));

// Early 5-minute-loop crops (levels 6, 8, 12). `amp` is the sway at the tip in pixels;
// `fixed` is the share of the sprite height, from the ground up, that never moves (the carrot's root).
export const IDLE_TARGETS = Object.freeze([
  {id: 'oats', amp: 2, lift: 1, fixed: 0.25},
  {id: 'carrot', amp: 2, lift: 1, fixed: 0.42},
  {id: 'lettuce', amp: 1, lift: 1, fixed: 0.25},
]);

// Frame 3 is the authored mature frame; 4..10 are derived from it.
const POSES = Object.freeze([
  {sway: 0.5, lift: 0}, {sway: 1, lift: 0}, {sway: -0.5, lift: 0}, {sway: -1, lift: 0},
  {sway: 0, lift: 1}, {sway: -1, lift: 1}, {sway: 1, lift: 1},
]);
export const IDLE_CLIP = Object.freeze({frames: [3, 4, 5, 4, 3, 6, 7, 6], durations: [520, 200, 260, 200, 360, 200, 260, 200], loop: true});
export const ACTION_CLIP = Object.freeze({frames: [8, 9, 10, 9, 10, 3], durations: [160, 140, 140, 140, 160, 200], loop: false});

/** Pure: shift rows of an RGBA buffer. Rows within the bottom `fixed` share of the sprite stay put. */
export function derivePose(src, width, height, bounds, {amp, lift, fixed = 0.25}, pose) {
  const out = Buffer.alloc(src.length);
  const top = bounds.y, base = bounds.y + bounds.h - 1, span = Math.max(1, base - top);
  for (let y = 0; y < height; y += 1) {
    const t = Math.max(0, Math.min(1, (base - y) / span));
    const weight = t < fixed ? 0 : ((t - fixed) / (1 - fixed)) ** 1.5;
    const dx = Math.round(amp * pose.sway * weight);
    const dy = Math.round(lift * pose.lift * weight);
    const sy = y + dy;
    for (let x = 0; x < width; x += 1) {
      const sx = x - dx;
      if (sx < 0 || sx >= width || sy < 0 || sy >= height) continue;
      src.copy(out, (y * width + x) * 4, (sy * width + sx) * 4, (sy * width + sx) * 4 + 4);
    }
  }
  return out;
}

async function main() {
  const sharp = loadSharp();
  globalThis.window = {};
  for (const f of ['motion-data.js', 'level-assets.js']) new Function(await fs.readFile(path.join(root, f), 'utf8'))();
  const items = new Map(window.FARM_MOTION.items.map((item) => [item.id, item]));
  const manifest = {version: 1, generatedBy: 'build-idle-assets.mjs', loadAfter: 'motion-care-data.js', method: 'whole-pixel row shifts of the authored mature frame; base share fixed per crop', items: []};
  for (const target of IDLE_TARGETS) {
    const item = items.get(target.id);
    const mature = item?.frames?.[3];
    if (!mature || item.frames.length !== 4) throw new Error(`${target.id}: expected the four authored growth frames`);
    const file = path.join(root, mature.file);
    const {data, info} = await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject: true});
    const frames = [];
    for (const [index, pose] of POSES.entries()) {
      const pixels = derivePose(data, info.width, info.height, mature.bounds, target, pose);
      const rel = path.posix.join(path.posix.dirname(mature.file), `frame-${String(index + 5).padStart(2, '0')}.png`);
      const png = await sharp(pixels, {raw: {width: info.width, height: info.height, channels: 4}}).png({compressionLevel: 9}).toBuffer();
      await fs.writeFile(path.join(root, rel), png);
      frames.push({file: rel, width: mature.width, height: mature.height, pivotX: mature.pivotX, pivotY: mature.pivotY, bounds: mature.bounds, derivedFrom: mature.file, pose, sha256: crypto.createHash('sha256').update(png).digest('hex')});
    }
    manifest.items.push({id: target.id, amp: target.amp, lift: target.lift, fixed: target.fixed, frames, clips: {idle: IDLE_CLIP, action: ACTION_CLIP}});
  }
  await fs.writeFile(path.join(root, 'idle-assets-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  await fs.writeFile(path.join(root, 'motion-idle-data.js'), `// Generated by build-idle-assets.mjs. Load after motion-care-data.js.
(() => {
  const manifest = ${JSON.stringify(manifest)};
  window.FARM_IDLE_ASSETS = manifest;
  const items = new Map((window.FARM_MOTION?.items || []).map((item) => [item.id, item]));
  for (const extra of manifest.items) {
    const item = items.get(extra.id);
    if (!item || item.__idleV249Applied) continue;
    if (item.frames.length !== 4) throw new Error('Idle assets expect four growth frames for ' + extra.id + '.');
    item.frames.push(...extra.frames);
    item.clips = {...(item.clips || {}), idle: extra.clips.idle, action: extra.clips.action};
    item.__idleV249Applied = true;
  }
})();
`);
  console.log('idle assets:', manifest.items.map((i) => `${i.id} +${i.frames.length}`).join(', '));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
