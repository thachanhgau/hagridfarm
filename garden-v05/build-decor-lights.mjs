const root=new URL('./',import.meta.url),manifest=JSON.parse(await fs.readFile(new URL('decor-assets-manifest.json',root))),scene=JSON.parse(await fs.readFile(new URL('scene-data.json',root)));
const assets=new Map([...manifest.items,...Object.entries(ITEM_ART).map(([id,a])=>({id,...a})),...Object.values(PLOT_SCENERY_ART),...Object.values(FESTIVAL_HEROES),...scene.props,{id:'pond-nook',...POND_SCENERY['pond-nook']}].map(a=>[a.id,a]));
