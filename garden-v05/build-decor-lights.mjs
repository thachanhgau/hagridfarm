async function points(asset,file,rect,density,limit,kind){
 const hd=density===2&&HD_ART[file],source=hd?.file||file,d=hd?.density||1;
 let image=sharp(fileURLToPath(new URL(source,root)));if(rect)image=image.extract({left:rect.x*d,top:rect.y*d,width:rect.w*d,height:rect.h*d});
 const {data,info}=await image.ensureAlpha().raw().toBuffer({resolveWithObject:true}),candidates=[];
 for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++){
  const i=(y*info.width+x)*4,r=data[i],g=data[i+1],b=data[i+2];
  // Keep actual luminous gold/cyan pixels. White snow and brown wood do not qualify.
  const gold=r>=225&&g>=170&&b<=195&&r>b*1.2,cyan=b>=200&&g>=170&&r<g*.95;
  if(data[i+3]<230||(!gold&&!cyan)||kind==='tree'&&y>info.height*.82)continue;
  candidates.push({x:Math.round(x/d*2)/2,y:Math.round(y/d*2)/2,score:r+g+b,color:gold?'255,207,116':'183,238,255'});
 }
 candidates.sort((a,b)=>b.score-a.score||a.y-b.y||a.x-b.x);
 const result=[];for(const p of candidates){if(result.every(q=>Math.hypot(q[0]-p.x,q[1]-p.y)>9)){result.push([p.x,p.y,p.color]);if(result.length===limit)break;}}
 // Dim skull frames still emit from an actual opaque highlight, never from empty canvas.
 if(!result.length){let best=-1,pixel;for(let i=0;i<data.length;i+=4)if(data[i+3]>230){const score=data[i]+data[i+1]+data[i+2];if(score>best){best=score;pixel=[(i/4%info.width)/d,Math.floor(i/4/info.width)/d,'255,207,116'];}}if(pixel)result.push(pixel);}
 return result;
}
const out={};
for(const [id,spec]of Object.entries(DECOR_LIGHTS)){
 const a=assets.get(id);if(!a?.file)throw Error('Missing emitter '+id);const views={};
 for(const facing of ['default','right']){
  const right=facing==='right',base=(right&&a.rightFile)||a.file,frames=(right&&a.rightFrames)||a.frames||[base],rects=right?a.rightAtlasRects:a.atlasRects;
  views[facing]=[];
  for(let i=0;i<frames.length;i++)views[facing].push({native:await points(a,frames[i],rects?.[i],1,spec.maxPoints,spec.kind),hd:await points(a,frames[i],rects?.[i],2,spec.maxPoints,spec.kind)});
 }
 out[id]=views;
}
await fs.writeFile(new URL('decor-light-points.mjs',root),'// Generated by build-decor-lights.mjs from current native/HD pixels; logical sprite coordinates.\nexport const DECOR_LIGHT_POINTS='+JSON.stringify(out)+';\n');
console.log('Emitter families:',Object.keys(out).length,'cells:',Object.values(out).reduce((n,a)=>n+a.default.length+a.right.length,0));
