const palette = SPRITE_PALETTE.map(hex => [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)));
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const records = {};
const colors = new Map();

function bounds(data, width, height) {
 let x0 = width, y0 = height, x1 = -1, y1 = -1;
 for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
  if (data[(y * width + x) * 4 + 3] < 192) continue;
  x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
 }
 if (x1 < 0) throw Error('Empty artwork');
 return {x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1};
}

// Transparent valleys protect silhouettes when generated grids are slightly uneven.
function cuts(data, width, height, count, horizontal) {
 const length = horizontal ? width : height;
 const projection = Array(length).fill(0);
 for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
  if (data[(y * width + x) * 4 + 3] >= 192) projection[horizontal ? x : y]++;
 }
 const edges = [0];
 for (let part = 1; part < count; part++) {
  const expected = length * part / count;
  const radius = length / count * 0.3;
  const candidates = [];
  for (let i = Math.ceil(expected - radius); i <= Math.floor(expected + radius); i++) {
   if (projection[i] === 0) candidates.push(i);
  }
  if (!candidates.length) throw Error(`No transparent atlas boundary at ${part}/${count}`);
  candidates.sort((a, b) => Math.abs(a - expected) - Math.abs(b - expected));
  edges.push(candidates[0]);
 }
 return [...edges, length];
}

function nearest(r, g, b) {
 const key = (r << 16) | (g << 8) | b;
 if (!colors.has(key)) colors.set(key, palette.reduce((best, p) => {
  const distance = (p[0] - r) ** 2 + (p[1] - g) ** 2 + (p[2] - b) ** 2;
  return distance < best.distance ? {p, distance} : best;
 }, {p: palette[0], distance: Infinity}).p);
 return colors.get(key);
}

async function emit(id, raw, source) {
 const {data, info: {width, height}} = raw;
 const b = bounds(data, width, height);
 const decor = id.startsWith('decoration-');
 const supply = /^(supply_|premium_)/.test(id);
 const pen = /^pen_\d+$/.test(id);
 const largePen = /^pen_[4-6]$/.test(id);
 const frameWidth = pen ? (largePen ? 160 : 128) : decor ? 96 : 64;
 const frameHeight = pen ? (largePen ? 144 : 112) : decor ? 112 : 64;
 const pivotX = frameWidth / 2, pivotY = pen ? frameHeight - 16 : decor ? 96 : 56;
 // Supply icons must fit the inventory's 40px slot at native 1x as well as the shop.
 const maxWidth = supply ? 40 : pen ? (largePen ? 144 : 112) : decor ? 84 : 52;
 const maxHeight = supply ? 40 : pen ? (largePen ? 112 : 88) : decor ? 80 : 48;
 const scale = Math.min(maxWidth / b.w, maxHeight / b.h, 1);
 const w = Math.max(1, Math.round(b.w * scale)), h = Math.max(1, Math.round(b.h * scale));
 const left = Math.floor((frameWidth - w) / 2), top = pivotY - h;
 const output = Buffer.alloc(frameWidth * frameHeight * 4);
 for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
  const sx = b.x + Math.min(b.w - 1, Math.floor((x + 0.5) * b.w / w));
  const sy = b.y + Math.min(b.h - 1, Math.floor((y + 0.5) * b.h / h));
  const i = (sy * width + sx) * 4;
  if (data[i + 3] < 192) continue;
  const j = ((top + y) * frameWidth + left + x) * 4;
  output.set([...nearest(data[i], data[i + 1], data[i + 2]), 255], j);
 }
 const file = `native-items/${id}.png`;
 const png = await sharp(output, {raw: {width: frameWidth, height: frameHeight, channels: 4}}).png().toBuffer();
 await fs.writeFile(path.join(root, file), png);
 records[id] = {file, width: frameWidth, height: frameHeight, pivotX, pivotY, bounds: bounds(output, frameWidth, frameHeight), sha256: sha256(png), ...source};
}

async function writeModule() {
 const lines = Object.entries(records).map(([id, record]) => {
  const {file, rightFile, width, height, pivotX, pivotY, bounds, rightBounds} = record;
  return ` ${JSON.stringify(id)}: ${JSON.stringify({file, rightFile, width, height, pivotX, pivotY, bounds, rightBounds})}`;
 });
 await fs.writeFile(path.join(root, 'item-art.mjs'), `// Generated by build-item-art.mjs; masters and provenance are not runtime inputs.\nexport const ITEM_ART = Object.freeze({\n${lines.join(',\n')}\n});\n`);
}

await fs.mkdir(path.join(root, 'native-items'), {recursive: true});
const config = JSON.parse(await fs.readFile(path.join(root, 'item-art-sources.json'), 'utf8'));
const decorations = JSON.parse(await fs.readFile(path.join(root, 'earned-decor-art-sources.json'), 'utf8'));
config.groups.push(...decorations.groups);
const supplies = JSON.parse(await fs.readFile(path.join(root, 'supply-art-sources.json'), 'utf8'));
config.groups.push(...supplies.groups);
for (const group of config.groups) {
 const source = `masters-items/${group.name}.png`;
 const bytes = await fs.readFile(path.join(root, source));
 const raw = await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject: true});
 const {width, height} = raw.info;
 const ys = cuts(raw.data, width, height, group.rows, false);
 for (let i = 0; i < group.items.length; i++) {
  const col = i % group.columns, row = Math.floor(i / group.columns);
  const rowRaw = await sharp(bytes).extract({left: 0, top: ys[row], width, height: ys[row + 1] - ys[row]}).ensureAlpha().raw().toBuffer({resolveWithObject: true});
  const xs = cuts(rowRaw.data, rowRaw.info.width, rowRaw.info.height, group.columns, true);
  const rect = {left: xs[col], top: ys[row], width: xs[col + 1] - xs[col], height: ys[row + 1] - ys[row]};
  const cell = await sharp(bytes).extract(rect).ensureAlpha().raw().toBuffer({resolveWithObject: true});
  const b = bounds(cell.data, cell.info.width, cell.info.height);
  if ((col === 0 && b.x === 0) || (row === 0 && b.y === 0) ||
      (col === group.columns - 1 && b.x + b.w === rect.width) ||
      (row === group.rows - 1 && b.y + b.h === rect.height)) throw Error(`Clipped atlas edge: ${group.items[i][0]}`);
  await emit(group.items[i][0], cell, {source, sourceSha256: sha256(bytes), sourceRect: rect});
 }
}
for (const group of decorations.groups) {
 const base = records[group.name], right = records[`${group.name}_right`];
 base.rightFile = right.file;
 base.rightBounds = right.bounds;
}
// Build compact pen icons from the actual enclosure geometry, never the rejected roofs.
for(let i=1;i<=6;i++){
 const pen={id:'pen_'+i,col:0,row:0,width:5,height:3},rects=[];
 const iso=(col,row)=>[112+(col-row)*24,40+(col+row)*12];
 const ctx={save(){},restore(){},fillRect(x,y,w,h){rects.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${this.fillStyle}"/>`);}};
 const corners=[[0,0],[5,0],[5,3],[0,3]].map(([col,row])=>iso(col,row));
 drawPenHabitat(ctx,{corners,pen,iso});
 for(const piece of penFencePieces(pen,iso))drawPenFence(ctx,piece);
 const svg=Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="256" height="160">${rects.join('')}</svg>`);
 const source='garden-pen-details.mjs';
 await emit(pen.id,await sharp(svg).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{source,sourceSha256:sha256(await fs.readFile(path.join(root,source))),sourceType:'perimeter-fence'});
}
await writeModule();
await fs.writeFile(path.join(root, 'item-art-manifest.json'), JSON.stringify({version: 1, palette: SPRITE_PALETTE, alphaThreshold: 192, items: records}, null, 2) + '\n');
