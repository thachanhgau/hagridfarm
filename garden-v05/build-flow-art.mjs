// Export authored ImageGen masters through the existing native palette/pivot pipeline.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {authoredCells} from './authored-atlas.mjs';
import {exportSprite,bounds} from './build-complete-objects.mjs';
import {packNativeAtlas} from './native-atlas.mjs';
const root=path.dirname(fileURLToPath(import.meta.url));
const sharp=createRequire(import.meta.url)('/Users/thachanh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const source=JSON.parse(await fs.readFile(path.join(root,'flow-art-sources.json')));
const items=[],crops=[];
for(const record of source.items){
 const bytes=await fs.readFile(path.join(root,record.master)),masterSha256=hash(bytes);
 const raw=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 if(record.kind==='crop'){
  let poses=authoredCells(raw,[4,4,4,2]);
  if(record.id==='flitterbloom')poses=poses.filter((_,i)=>i!==7);
  for(const pose of poses){
   const b=pose.mainBounds,base=[];
   for(let y=Math.max(0,b.y+b.h-Math.max(2,Math.round(b.h*.08)));y<b.y+b.h;y++)for(let x=b.x;x<b.x+b.w;x++)if(pose.data[(y*pose.width+x)*4+3]>=192)base.push(x);
   base.sort((a,b)=>a-b);pose.anchorX=base[Math.floor(base.length/2)]+.5;
  }
  const target={width:64,height:96,pivotX:32,pivotY:80,maxWidth:54,maxHeight:60};
  let scale=Math.min(target.maxWidth/Math.max(...poses.map(p=>p.bounds.w)),target.maxHeight/Math.max(...poses.map(p=>p.bounds.h)));
  for(const p of poses)scale=Math.min(scale,29/Math.max(1,p.anchorX-p.bounds.x),29/Math.max(1,p.bounds.x+p.bounds.w-p.anchorX));
  const frames=[];
  for(const [i,pose]of poses.entries())frames.push(await exportSprite({...record,id:'flow-'+record.id,outputFolder:'native-crop-complete'},pose,i,target,scale));
  // UI crop and seed icons use standalone growth sprites; moving poses share an atlas.
  for(let i=0;i<4;i++){
   const file=`native-levels/${record.id}/flow-v1-${i+1}.png`;
   await fs.copyFile(path.join(root,frames[i].file),path.join(root,file));frames[i]={...frames[i],file};
  }
  const atlas=await packNativeAtlas(root,`native-crop-complete/flow-${record.id}/atlas.png`,frames.slice(4));
  const idleCount=record.id==='flitterbloom'?3:4;
  const idle=Array.from({length:idleCount},(_,i)=>i+4);
  const clips={growth:{frames:[0,1,2,3],durations:[900,900,900,900],loop:false},idle:{frames:[...idle,...idle.slice(1,-1).reverse()],durations:idleCount===3?[600,300,520,300]:[500,240,180,440,240,240],loop:true},action:{frames:Array.from({length:6},(_,i)=>4+idleCount+i),durations:[160,140,140,140,160,200],loop:false}};
  const runtimeFrames=[...frames.slice(0,4).map(({sha256,sourceRect,...f})=>f),...atlas.frames];
  crops.push({id:record.id,frames:runtimeFrames,clips});
  items.push({...record,masterSha256,frames,atlas,clips});
 }else{
  const b=bounds(raw.data,raw.info.width,raw.info.height),pose={data:raw.data,width:raw.info.width,height:raw.info.height,bounds:b,sourceRect:{x:0,y:0,w:raw.info.width,h:raw.info.height}};
  const target={width:64,height:64,pivotX:32,pivotY:56,maxWidth:40,maxHeight:40};
  const frame=await exportSprite({...record,outputFolder:'native-items'},pose,0,target,Math.min(40/b.w,40/b.h));
  items.push({...record,masterSha256,...frame});
 }
}
const art=Object.fromEntries(items.filter(i=>i.kind!=='crop').map(i=>{const {file,width,height,pivotX,pivotY,bounds}=i;return [i.id,{file,width,height,pivotX,pivotY,bounds}]}));
await fs.writeFile(path.join(root,'flow-item-art.mjs'),`// Generated by build-flow-art.mjs; full prompts and provenance stay in source.\nexport const FLOW_ITEM_ART=Object.freeze(${JSON.stringify(art,null,2)});\n`);
await fs.writeFile(path.join(root,'flow-crop-data.js'),`// Generated by build-flow-art.mjs; load after crop-complete-data.js.\n(()=>{const records=${JSON.stringify(crops)};for(const record of records){const item=window.FARM_MOTION.items.find(i=>i.id===record.id);if(!item)throw Error('Missing crop '+record.id);item.frames=record.frames;item.clips={...item.clips,...record.clips};item.__authoredFlowArt=true;}window.FARM_FLOW_CROPS=records.map(i=>i.id);})();\n`);
await fs.writeFile(path.join(root,'flow-art-manifest.json'),JSON.stringify({version:1,tool:'builtin image_gen',method:'authored cells; common root pivot; native palette24 and binary alpha; lossless atlas RGBA checks',items},null,2)+'\n');
console.log(JSON.stringify({crops:crops.length,cropFrames:crops.reduce((n,c)=>n+c.frames.length,0),icons:Object.keys(art).length}));
