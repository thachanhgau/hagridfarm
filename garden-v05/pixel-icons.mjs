/** Rows → SVG with one rect per horizontal run of a colour (16×16, or any size such as the envelope). */
export function iconSvg(rows) {
 let rects = '';
 rows.forEach((row, y) => {
  for (let x = 0; x < row.length;) {
   const ch = row[x];
   let end = x + 1;
   while (row[end] === ch) end += 1;
   if (INK[ch]) rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${INK[ch]}"/>`;
   x = end;
  }
 });
 return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${rows[0].length} ${rows.length}" shape-rendering="crispEdges">${rects}</svg>`;
}

const urls = new Map();
export function iconUrl(name) {
 if (!urls.has(name)) urls.set(name, 'data:image/svg+xml,' + encodeURIComponent(iconSvg(ICONS[name] || ICONS.xp)));
 return urls.get(name);
}

/** A decorative pixel icon at an integer scale (1 → 16 px, 2 → 32 px). */
export function pixelIcon(name, scale = 2) {
 const size = 16 * scale;
 return el('img', {class: 'px-icon', src: iconUrl(name), alt: '', 'aria-hidden': 'true', width: size, height: size, 'data-icon': name, draggable: 'false'});
}

/** Which line of the plot is chosen, as a 3×3 mini plot (seed options button). */
export function lineIconUrl(cells) {
 const on = new Set(cells), rows = Array.from({length: 16}, () => [...'................']);
 for (let i = 0; i < 9; i += 1) {
  const x0 = 1 + (i % 3) * 5, y0 = 1 + Math.floor(i / 3) * 5;
  for (let y = y0; y < y0 + 4; y += 1) for (let x = x0; x < x0 + 4; x += 1) {
   const edge = x === x0 || y === y0 || x === x0 + 3 || y === y0 + 3;
   rows[y][x] = on.has(i) ? (edge ? 'O' : 'Y') : (edge ? 'k' : 'b');
  }
 }
 return 'data:image/svg+xml,' + encodeURIComponent(iconSvg(rows.map((r) => r.join(''))));
}

/**
 * Icon-first action button: [icon] short label, optional count badge (×3).
 * `text` stays the accessible name and tooltip, so the full sentence is never lost.
 */
export function setAction(buttonEl, {icon, label = '', count = '', text = label, sprite = null}) {
 const key = [icon, sprite ? 'sprite' : '', label, count].join('|');
 if (buttonEl.dataset?.actionKey !== key) {
  const parts = [sprite || pixelIcon(icon, 2), el('span', {class: 'action-label', text: label})];
  if (count) parts.push(el('b', {class: 'action-count', text: count}));
  buttonEl.replaceChildren(...parts);
  if (buttonEl.dataset) buttonEl.dataset.actionKey = key;
  else buttonEl.setAttribute('data-action-key', key);
 }
 buttonEl.setAttribute('aria-label', text);
 buttonEl.title = text;
}

/**
 * Cost chips for crafting, building and decorations: each item as icon + have/need,
 * then Galleons as a coin + price (`galleonShort` marks a wallet that cannot pay).
 */
export function costChips(items, costs, galleons = 0, galleonShort = false) {
 const chips = costs.map(({id, have, need}) => el('span', {class: 'dock-cost' + (have < need ? ' is-short' : ''), 'aria-hidden': 'true'},
  [visualItemIcon(items, id, {size: 22}), el('span', {text: `${num(have)}/${num(need)}`})]));
 if (galleons) chips.push(el('span', {class: 'dock-cost is-galleons' + (galleonShort ? ' is-short' : ''), 'aria-hidden': 'true'}, [pixelIcon('coin', 1), el('span', {text: num(galleons)})]));
 return chips;
}

/** A reward as icon + number chips ([water] +8 [pumpkin] +3); the full sentence stays the accessible name. */
export function rewardChips(items, reward = {}) {
 const chips = [], add = (node, n) => chips.push(el('span', {class: 'reward-chip'}, [node, el('b', {text: '+' + num(n)})]));
 if (reward.kind === 'water' && reward.amount) add(pixelIcon('water', 1), reward.amount);
 if (reward.kind === 'boost' && reward.amount) add(pixelIcon('boost', 1), reward.amount);
 if (reward.waterBonus) add(pixelIcon('water', 1), reward.waterBonus);
 if (reward.itemId && reward.bonusQty) add(visualItemIcon(items, reward.itemId, {size: 20}), reward.bonusQty);
 if (reward.eventPoints) add(pixelIcon('festival', 1), reward.eventPoints);
 if (!chips.length && reward.label) chips.push(el('span', {class: 'reward-chip', text: reward.label}));
 return el('span', {class: 'reward-chips', role: 'img', 'aria-label': reward.label || '', title: reward.label || ''}, chips);
}

