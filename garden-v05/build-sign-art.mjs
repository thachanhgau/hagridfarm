// Convert the selected transparent master to native pixels; preserve the recovery master.
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {SPRITE_PALETTE} from './palette.mjs';
const require=createRequire(import.meta.url),sharp=require('/Users/thachanh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root=new URL('./',import.meta.url),source='masters/hagrid-farm-sign-v01.png',bytes=await fs.readFile(new URL(source,root));
const {data,info}=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const shear=.17,threshold=192;let left=info.width,right=0,top=Infinity,bottom=-Infinity;
for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>=threshold){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y+shear*x);bottom=Math.max(bottom,y+shear*x);}
const width=288,height=288,scale=Math.min(264/(right-left+1),256/(bottom-top+1)),w=Math.round((right-left+1)*scale),h=Math.round((bottom-top+1)*scale),dx=Math.floor((width-w)/2),dy=272-h;
const palette=SPRITE_PALETTE.map(hex=>[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16))),colors=new Map(),output=Buffer.alloc(width*height*4);
function nearest(r,g,b){const key=(r<<16)|(g<<8)|b;if(!colors.has(key)){let best=palette[0],distance=Infinity;for(const p of palette){const d=(p[0]-r)**2+(p[1]-g)**2+(p[2]-b)**2;if(d<distance){best=p;distance=d;}}colors.set(key,best);}return colors.get(key);}
for(let y=0;y<h;y++)for(let x=0;x<w;x++){
 const sx=Math.round(left+(x+.5)/scale),sy=Math.round(top+(y+.5)/scale-shear*sx);
 if(sx<0||sy<0||sx>=info.width||sy>=info.height)continue;
 const i=(sy*info.width+sx)*4;if(data[i+3]<threshold)continue;
 output.set([...nearest(data[i],data[i+1],data[i+2]),255],((y+dy)*width+x+dx)*4);
}
const file='environment/layers/hagrid-farm-sign.png',png=await sharp(output,{raw:{width,height,channels:4}}).png().toBuffer();
await fs.writeFile(new URL(file,root),png);
const point=(x,y)=>({x:dx+(x-left)*scale,y:dy+(y+shear*x-top)*scale});
const text=point(400,365),art={file,width,height,text:{x:Math.round(text.x),y:Math.round(text.y),slope:.5,maxWidth:Math.floor(740*scale),lineGap:Math.round(62*scale)}};
await fs.writeFile(new URL('farm-sign-art.mjs',root),'// Generated by build-sign-art.mjs. Text is projected onto the sign face at runtime.\nexport const FARM_SIGN_ART=Object.freeze('+JSON.stringify(art)+');\n');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
await fs.writeFile(new URL('farm-sign-art-manifest.json',root),JSON.stringify({source,sourceSha256:hash(bytes),file,sha256:hash(png),width,height,alphaThreshold:threshold,palette:SPRITE_PALETTE,verticalShear:shear,...art},null,2)+'\n');
